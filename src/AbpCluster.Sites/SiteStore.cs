using System.Globalization;
using System.Security.Cryptography;
using Npgsql;

namespace AbpCluster.Sites;

/// <summary>
/// The sites' tables in plain SQL: read before the app starts and on a replica, where there's no DbContext, and changed
/// by a site's first start, a takeover, a site standing down or a hand-over, each in one transaction under a lock, so two
/// servers of a site never change it twice. The tables live in <see cref="SitesOptions.Schema"/>; a host whose tables
/// are already there (made by its own migrations, in the same shape) names that schema, and
/// <see cref="EnsureTablesAsync"/> leaves them as they are.
/// </summary>
public sealed class SiteStore(SitesOptions options)
{
    private readonly string _s = options.QuotedSchema;

    /// <summary>The lock every running app holds shared for its life, so a hand-over knows when all of a site's apps have stopped.</summary>
    internal string AppLock => options.LockKey("site-app");

    /// <summary>The database's state now; throws when it can't be reached within a few seconds.</summary>
    public static async Task<SiteDatabaseDto> ReadDatabaseAsync(string connectionString, CancellationToken cancellationToken)
    {
        NpgsqlConnectionStringBuilder builder = new(connectionString) { Timeout = 5, CommandTimeout = 5 };
        await using NpgsqlConnection connection = new(builder.ConnectionString);
        await connection.OpenAsync(cancellationToken);
        // On a primary the replay functions give nulls. None of them needs more than the app's own role.
        await using NpgsqlCommand read = new("""
            SELECT pg_is_in_recovery(),
                   pg_last_xact_replay_timestamp(),
                   pg_wal_lsn_diff(pg_last_wal_receive_lsn(), pg_last_wal_replay_lsn())::bigint,
                   pg_last_wal_receive_lsn()::text,
                   pg_last_wal_replay_lsn()::text
            """, connection);
        await using NpgsqlDataReader row = await read.ExecuteReaderAsync(cancellationToken);
        await row.ReadAsync(cancellationToken);
        return new SiteDatabaseDto(
            row.GetBoolean(0),
            row.IsDBNull(1) ? null : row.GetFieldValue<DateTimeOffset>(1),
            row.IsDBNull(2) ? null : row.GetInt64(2),
            row.IsDBNull(3) ? null : row.GetString(3),
            row.IsDBNull(4) ? null : row.GetString(4));
    }

    /// <summary>Makes the schema and its tables where they aren't. Only on a writable database, at the app's start.</summary>
    public async Task EnsureTablesAsync(NpgsqlConnection connection, CancellationToken cancellationToken)
    {
        await using NpgsqlCommand make = new($"""
            CREATE SCHEMA IF NOT EXISTS {_s};
            CREATE TABLE IF NOT EXISTS {_s}.sites (
                "Name" varchar(32) PRIMARY KEY, "Label" varchar(100) NOT NULL, "Address" varchar(500) NOT NULL,
                "CreatedAt" timestamptz NOT NULL, "UpdatedAt" timestamptz NOT NULL);
            CREATE TABLE IF NOT EXISTS {_s}.site_state (
                "Id" integer PRIMARY KEY, "Site" varchar(32) NOT NULL, "Epoch" bigint NOT NULL, "Timeline" integer NULL,
                "Since" timestamptz NOT NULL, "Reason" varchar(32) NOT NULL,
                "HandingTo" varchar(32) NULL, "HandingPhase" varchar(16) NULL, "HandingSince" timestamptz NULL);
            CREATE TABLE IF NOT EXISTS {_s}.site_changes (
                "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "Epoch" bigint NOT NULL, "Site" varchar(32) NOT NULL,
                "PreviousSite" varchar(32) NULL, "Timeline" integer NULL, "Reason" varchar(32) NOT NULL, "KeyGap" bigint NULL,
                "At" timestamptz NOT NULL, "Note" varchar(500) NULL);
            CREATE TABLE IF NOT EXISTS {_s}.site_lag_spells (
                "Site" varchar(32) PRIMARY KEY, "Since" timestamptz NOT NULL, "Told" boolean NOT NULL DEFAULT false);
            CREATE TABLE IF NOT EXISTS {_s}.site_signing_key (
                "Id" integer PRIMARY KEY, "Key" bytea NOT NULL, "CreatedAt" timestamptz NOT NULL);
            """, connection);
        await make.ExecuteNonQueryAsync(cancellationToken);
    }

    /// <summary>
    /// The active site, or null when no site has claimed this database yet (or its tables aren't made yet). A table from
    /// before the planned switchover (no hand-over columns) is read without them.
    /// </summary>
    public async Task<ActiveSiteDto?> ReadActiveAsync(NpgsqlConnection connection, CancellationToken cancellationToken, NpgsqlTransaction? transaction = null)
    {
        try
        {
            return await ReadActiveAsync(connection, transaction, $"""
                SELECT "Site", "Epoch", "Timeline", "Since", "Reason", "HandingTo", "HandingPhase", "HandingSince"
                FROM {_s}.site_state WHERE "Id" = 1
                """, cancellationToken);
        }
        catch (PostgresException ex) when (ex.SqlState == PostgresErrorCodes.UndefinedTable || ex.SqlState == PostgresErrorCodes.InvalidSchemaName)
        {
            return null;
        }
        catch (PostgresException ex) when (ex.SqlState == PostgresErrorCodes.UndefinedColumn)
        {
            return await ReadActiveAsync(connection, transaction, $"""
                SELECT "Site", "Epoch", "Timeline", "Since", "Reason", NULL::text, NULL::text, NULL::timestamptz
                FROM {_s}.site_state WHERE "Id" = 1
                """, cancellationToken);
        }
    }

    private static async Task<ActiveSiteDto?> ReadActiveAsync(NpgsqlConnection connection, NpgsqlTransaction? transaction, string sql, CancellationToken cancellationToken)
    {
        await using NpgsqlCommand read = new(sql, connection, transaction);
        await using NpgsqlDataReader row = await read.ExecuteReaderAsync(cancellationToken);
        return await row.ReadAsync(cancellationToken) ? ActiveFrom(row) : null;
    }

    /// <summary>The sites, by name; none when their table isn't made yet.</summary>
    public async Task<List<SiteRecord>> SitesAsync(NpgsqlConnection connection, CancellationToken cancellationToken)
    {
        try
        {
            await using NpgsqlCommand read = new($"""SELECT "Name", "Label", "Address" FROM {_s}.sites ORDER BY "Name" """, connection);
            await using NpgsqlDataReader row = await read.ExecuteReaderAsync(cancellationToken);
            List<SiteRecord> sites = [];
            while (await row.ReadAsync(cancellationToken))
            {
                sites.Add(new SiteRecord(row.GetString(0), row.GetString(1), row.GetString(2)));
            }

            return sites;
        }
        catch (PostgresException ex) when (ex.SqlState == PostgresErrorCodes.UndefinedTable || ex.SqlState == PostgresErrorCodes.InvalidSchemaName)
        {
            return [];
        }
    }

    /// <summary>The latest changes of the active site, newest first.</summary>
    public async Task<List<SiteChangeDto>> ChangesAsync(NpgsqlConnection connection, int take, CancellationToken cancellationToken)
    {
        await using NpgsqlCommand read = new($"""
            SELECT "Epoch", "Site", "PreviousSite", "Timeline", "Reason", "KeyGap", "At", "Note"
            FROM {_s}.site_changes ORDER BY "Id" DESC LIMIT @take
            """, connection);
        read.Parameters.AddWithValue("take", take);
        await using NpgsqlDataReader row = await read.ExecuteReaderAsync(cancellationToken);
        List<SiteChangeDto> changes = [];
        while (await row.ReadAsync(cancellationToken))
        {
            changes.Add(new SiteChangeDto(row.GetInt64(0), row.GetString(1), row.IsDBNull(2) ? null : row.GetString(2),
                row.IsDBNull(3) ? null : row.GetInt32(3), row.GetString(4), row.IsDBNull(5) ? null : row.GetInt64(5),
                Utc(row.GetDateTime(6)), row.IsDBNull(7) ? null : row.GetString(7)));
        }

        return changes;
    }

    /// <summary>Adds a site, or changes its label and address. False when adding one whose name is taken.</summary>
    public async Task<bool> SaveSiteAsync(NpgsqlConnection connection, SiteRecord site, bool adding, CancellationToken cancellationToken)
    {
        await using NpgsqlCommand write = new(adding
            ? $"""
               INSERT INTO {_s}.sites ("Name", "Label", "Address", "CreatedAt", "UpdatedAt") VALUES (@name, @label, @address, now(), now())
               ON CONFLICT ("Name") DO NOTHING
               """
            : $"""UPDATE {_s}.sites SET "Label" = @label, "Address" = @address, "UpdatedAt" = now() WHERE "Name" = @name""", connection);
        write.Parameters.AddWithValue("name", site.Name);
        write.Parameters.AddWithValue("label", site.Label);
        write.Parameters.AddWithValue("address", site.Address);
        return await write.ExecuteNonQueryAsync(cancellationToken) > 0;
    }

    /// <summary>Removes a site from the list. False when there was none.</summary>
    public async Task<bool> RemoveSiteAsync(NpgsqlConnection connection, string name, CancellationToken cancellationToken)
    {
        await using NpgsqlCommand delete = new($"""DELETE FROM {_s}.sites WHERE "Name" = @name""", connection);
        delete.Parameters.AddWithValue("name", name);
        return await delete.ExecuteNonQueryAsync(cancellationToken) > 0;
    }

    /// <summary>
    /// The database's timeline: 1 until it's promoted from a replica, then one more at each promotion. Read from the name
    /// of the WAL file it writes now, which needs no privilege; null on a replica, or where the database doesn't say.
    /// </summary>
    public static async Task<int?> TimelineAsync(NpgsqlConnection connection, CancellationToken cancellationToken)
    {
        try
        {
            await using NpgsqlCommand read = new("SELECT pg_walfile_name(pg_current_wal_lsn())", connection);
            return await read.ExecuteScalarAsync(cancellationToken) is string { Length: >= 8 } name
                   && int.TryParse(name[..8], NumberStyles.HexNumber, CultureInfo.InvariantCulture, out int timeline)
                ? timeline
                : null;
        }
        catch (PostgresException)
        {
            return null;
        }
    }

    /// <summary>
    /// Changes the active site if <paramref name="decide"/>, given the row as it is under the lock, returns a change: the
    /// row, a line of history, the site's own row when it has none, and, on a takeover or switchover,
    /// <paramref name="takeoverSteps"/> in the same transaction. Returns the row as it is after.
    /// </summary>
    internal async Task<ActiveSiteDto?> ChangeAsync(
        NpgsqlConnection connection, Func<ActiveSiteDto?, SiteChangePlan?> decide, IReadOnlyList<SiteTakeoverStep> takeoverSteps,
        CancellationToken cancellationToken)
    {
        await using NpgsqlTransaction transaction = await connection.BeginTransactionAsync(cancellationToken);
        // A lock for the transaction rather than FOR UPDATE: there may be no row to lock yet.
        await using (NpgsqlCommand take = new($"SELECT pg_advisory_xact_lock({options.LockKey("site-state")})", connection, transaction))
        {
            await take.ExecuteNonQueryAsync(cancellationToken);
        }

        ActiveSiteDto? current = await ReadActiveAsync(connection, cancellationToken, transaction);
        if (decide(current) is not { } plan)
        {
            await transaction.CommitAsync(cancellationToken);
            return current;
        }

        await using (NpgsqlCommand write = new($"""
            INSERT INTO {_s}.site_state ("Id", "Site", "Epoch", "Timeline", "Since", "Reason")
            VALUES (1, @site, @epoch, @timeline, @since, @reason)
            ON CONFLICT ("Id") DO UPDATE SET "Site" = EXCLUDED."Site", "Epoch" = EXCLUDED."Epoch", "Timeline" = EXCLUDED."Timeline",
                "Since" = EXCLUDED."Since", "Reason" = EXCLUDED."Reason",
                "HandingTo" = NULL, "HandingPhase" = NULL, "HandingSince" = NULL;
            INSERT INTO {_s}.site_changes ("Epoch", "Site", "PreviousSite", "Timeline", "Reason", "KeyGap", "At", "Note")
            VALUES (@epoch, @site, @previous, @timeline, @reason, @gap, @at, @note);
            INSERT INTO {_s}.sites ("Name", "Label", "Address", "CreatedAt", "UpdatedAt")
            VALUES (@self, @self, '', @at, @at)
            ON CONFLICT ("Name") DO NOTHING;
            """, connection, transaction))
        {
            write.Parameters.AddWithValue("site", plan.Site);
            write.Parameters.AddWithValue("epoch", plan.Epoch);
            write.Parameters.AddWithValue("timeline", (object?)plan.Timeline ?? DBNull.Value);
            write.Parameters.AddWithValue("since", DateTime.SpecifyKind(plan.Since, DateTimeKind.Utc));
            write.Parameters.AddWithValue("reason", plan.Reason);
            write.Parameters.AddWithValue("previous", (object?)plan.PreviousSite ?? DBNull.Value);
            write.Parameters.AddWithValue("gap", (object?)plan.KeyGap ?? DBNull.Value);
            write.Parameters.AddWithValue("at", DateTime.UtcNow);
            write.Parameters.AddWithValue("note", (object?)plan.Note ?? DBNull.Value);
            write.Parameters.AddWithValue("self", plan.Self);
            await write.ExecuteNonQueryAsync(cancellationToken);
        }

        if (plan.Reason is SiteReasons.Takeover or SiteReasons.Switchover && plan.PreviousSite is { } previous)
        {
            SiteTakeover takeover = new(plan.Site, previous, plan.Epoch, plan.KeyGap ?? 0, plan.Switchover);
            foreach (SiteTakeoverStep step in takeoverSteps)
            {
                await step(connection, transaction, takeover, cancellationToken);
            }
        }

        ActiveSiteDto? after = await ReadActiveAsync(connection, cancellationToken, transaction);
        await transaction.CommitAsync(cancellationToken);
        return after;
    }

    /// <summary>Starts a planned switchover: the active site, <paramref name="site"/>, hands over to <paramref name="to"/>. False when it isn't active or already hands over.</summary>
    public async Task<bool> BeginHandoverAsync(NpgsqlConnection connection, string site, string to, CancellationToken cancellationToken)
    {
        await using NpgsqlCommand write = new($"""
            WITH started AS (
                UPDATE {_s}.site_state SET "HandingTo" = @to, "HandingPhase" = @phase, "HandingSince" = @at
                WHERE "Id" = 1 AND "Site" = @site AND "HandingTo" IS NULL
                RETURNING "Epoch", "Timeline")
            INSERT INTO {_s}.site_changes ("Epoch", "Site", "PreviousSite", "Timeline", "Reason", "At", "Note")
            SELECT "Epoch", @site, NULL, "Timeline", @reason, @at, @note FROM started
            """, connection);
        write.Parameters.AddWithValue("site", site);
        write.Parameters.AddWithValue("to", to);
        write.Parameters.AddWithValue("phase", HandoverPhases.Draining);
        write.Parameters.AddWithValue("at", DateTime.UtcNow);
        write.Parameters.AddWithValue("reason", SiteReasons.HandoverStarted);
        write.Parameters.AddWithValue("note", $"{site} began handing over to {to}.");
        return await write.ExecuteNonQueryAsync(cancellationToken) > 0;
    }

    /// <summary>
    /// The hand-over's last write, once no app of the site holds the shared app lock: the other site may take over now.
    /// False while one still does, or when there's no hand-over draining.
    /// </summary>
    public async Task<bool> ReadyHandoverAsync(NpgsqlConnection connection, CancellationToken cancellationToken)
    {
        await using (NpgsqlCommand take = new($"SELECT pg_try_advisory_lock({AppLock})", connection))
        {
            if (await take.ExecuteScalarAsync(cancellationToken) is not true)
            {
                return false;
            }
        }

        try
        {
            await using NpgsqlCommand write = new($"""
                UPDATE {_s}.site_state SET "HandingPhase" = @ready WHERE "Id" = 1 AND "HandingPhase" = @draining
                """, connection);
            write.Parameters.AddWithValue("ready", HandoverPhases.Ready);
            write.Parameters.AddWithValue("draining", HandoverPhases.Draining);
            return await write.ExecuteNonQueryAsync(cancellationToken) > 0;
        }
        finally
        {
            await using NpgsqlCommand release = new($"SELECT pg_advisory_unlock({AppLock})", connection);
            await release.ExecuteScalarAsync(cancellationToken);
        }
    }

    /// <summary>Calls a hand-over off: the site is active again as it was. False when there was none.</summary>
    public async Task<bool> CancelHandoverAsync(NpgsqlConnection connection, string site, CancellationToken cancellationToken)
    {
        await using NpgsqlCommand write = new($"""
            WITH cancelled AS (
                UPDATE {_s}.site_state SET "HandingTo" = NULL, "HandingPhase" = NULL, "HandingSince" = NULL
                WHERE "Id" = 1 AND "Site" = @site AND "HandingTo" IS NOT NULL
                RETURNING "Epoch", "Timeline")
            INSERT INTO {_s}.site_changes ("Epoch", "Site", "PreviousSite", "Timeline", "Reason", "At", "Note")
            SELECT "Epoch", @site, NULL, "Timeline", @reason, @at, @note FROM cancelled
            """, connection);
        write.Parameters.AddWithValue("site", site);
        write.Parameters.AddWithValue("at", DateTime.UtcNow);
        write.Parameters.AddWithValue("reason", SiteReasons.HandoverCancelled);
        write.Parameters.AddWithValue("note", "Called off with the break-glass key before the other site took over.");
        return await write.ExecuteNonQueryAsync(cancellationToken) > 0;
    }

    /// <summary>How far, in bytes, a standby that has replayed up to <paramref name="replayedLsn"/> is behind this database.</summary>
    public static async Task<long?> BehindAsync(NpgsqlConnection connection, string? replayedLsn, CancellationToken cancellationToken)
    {
        if (replayedLsn is null)
        {
            return null;
        }

        try
        {
            await using NpgsqlCommand read = new("SELECT GREATEST(pg_wal_lsn_diff(pg_current_wal_lsn(), @lsn::pg_lsn), 0)::bigint", connection);
            read.Parameters.AddWithValue("lsn", replayedLsn);
            return await read.ExecuteScalarAsync(cancellationToken) is long behind ? behind : null;
        }
        catch (PostgresException)
        {
            return null;
        }
    }

    /// <summary>A standby's spell of lag: started now if it wasn't lagging, and whether it's been told. One statement, for whichever server looks.</summary>
    public async Task<(DateTime Since, bool Told)> SpellAsync(NpgsqlConnection connection, string standby, CancellationToken cancellationToken)
    {
        // An upsert that changes nothing returns the row either way: the new spell's start, or the one already running.
        await using NpgsqlCommand spell = new($"""
            INSERT INTO {_s}.site_lag_spells ("Site", "Since") VALUES (@site, now())
            ON CONFLICT ("Site") DO UPDATE SET "Site" = EXCLUDED."Site"
            RETURNING "Since", "Told"
            """, connection);
        spell.Parameters.AddWithValue("site", standby);
        await using NpgsqlDataReader row = await spell.ExecuteReaderAsync(cancellationToken);
        await row.ReadAsync(cancellationToken);
        return (DateTime.SpecifyKind(row.GetDateTime(0), DateTimeKind.Utc), row.GetBoolean(1));
    }

    /// <summary>The spell has been told: the next look says nothing until it ends and another starts.</summary>
    public async Task ToldAsync(NpgsqlConnection connection, string standby, CancellationToken cancellationToken)
    {
        await using NpgsqlCommand told = new($"""UPDATE {_s}.site_lag_spells SET "Told" = true WHERE "Site" = @site""", connection);
        told.Parameters.AddWithValue("site", standby);
        await told.ExecuteNonQueryAsync(cancellationToken);
    }

    /// <summary>The standby is read and caught up (or no longer this site's standby): its spell ends.</summary>
    public async Task EndSpellAsync(NpgsqlConnection connection, string standby, CancellationToken cancellationToken)
    {
        await using NpgsqlCommand end = new($"""DELETE FROM {_s}.site_lag_spells WHERE "Site" = @site""", connection);
        end.Parameters.AddWithValue("site", standby);
        await end.ExecuteNonQueryAsync(cancellationToken);
    }

    /// <summary>
    /// The installation's signing key: made on the first start of a writable database, then read; it reaches the other
    /// sites with the database.
    /// </summary>
    public async Task<byte[]> SigningKeyAsync(NpgsqlConnection connection, CancellationToken cancellationToken)
    {
        await using (NpgsqlCommand make = new($"""
            INSERT INTO {_s}.site_signing_key ("Id", "Key", "CreatedAt") VALUES (1, @key, now()) ON CONFLICT ("Id") DO NOTHING
            """, connection))
        {
            make.Parameters.AddWithValue("key", RandomNumberGenerator.GetBytes(32));
            await make.ExecuteNonQueryAsync(cancellationToken);
        }

        await using NpgsqlCommand read = new($"""SELECT "Key" FROM {_s}.site_signing_key WHERE "Id" = 1""", connection);
        return (byte[])(await read.ExecuteScalarAsync(cancellationToken))!;
    }

    private static DateTimeOffset Utc(DateTime value) => new(DateTime.SpecifyKind(value, DateTimeKind.Utc));

    private static ActiveSiteDto ActiveFrom(NpgsqlDataReader row) => new(
        row.GetString(0),
        row.GetInt64(1),
        row.IsDBNull(2) ? null : row.GetInt32(2),
        Utc(row.GetDateTime(3)),
        row.GetString(4),
        row.IsDBNull(5) ? null : row.GetString(5),
        row.IsDBNull(6) ? null : row.GetString(6),
        row.IsDBNull(7) ? null : Utc(row.GetDateTime(7)));
}
